#!/usr/bin/env python3
"""Modular Hamiltonian of a BALL for the oscillators on the kernel graph: is its kinetic part the conformal
Killing weight beta(r) = 2 pi (R^2 - r^2)/(2R)?  (second ingredient of the entropic principle (P2)).

Model (population level = infinite uniform node density, units xi = 1): omega(k)^2 = 2(1 - exp(-k^2/2)) + m^2
(long-wave speed 1), ground state X = 1/(2 omega), P = omega/2, both of the form (ultralocal constant) + smooth
kernel.  Flat ball of radius R in D = 2 (Bessel order nu = mu, angular sector mu) or D = 3 (nu = l + 1/2).
In the variable u = r^{(D-1)/2} phi every sector is a problem on [0, R] with measure dr; the kinetic energy is
(1/2) int pi_u^2 dr, so Bisognano-Wichmann/Hislop-Longo for a conformal field means: kinetic part of the modular
Hamiltonian K = (1/2) p^T N p + (1/2) x^T B x is multiplication by beta(r).

Discretisation without loss of the uncertainty relation: the subsystem generated by phi and pi smeared with the
first A Dirichlet modes psi_a(r) = N_a sqrt(r) J_nu(alpha_a r) of the ball (alpha_a <= amax).  Its covariances are
exact compressions, X_ab = f0 delta_ab + int k (f(k) - f0) Phi_a Phi_b dk with the closed Hankel transform
Phi_a(k) = sqrt2 s_a alpha_a J_nu(kR)/(alpha_a^2 - k^2), so X_A P_A >= 1/4 holds exactly and the symplectic
eigenvalues near 1/2 are resolved in high precision (mpmath; k-integral by graded Gauss-Legendre panels, error
below 1e-45).  N = P^{-1/2} U (eps nu) U^T P^{-1/2}, eps = log((nu+1/2)/(nu-1/2)); modes with nu^2 - 1/4 below
10^{-(dps-10)} are clipped (their number is printed; results unchanged between dps 60 and 75).
Control (exactly known answer): the free continuum scalar field, massless (conformal, N = beta exactly for the
full ball) and massive (same m, not conformal), on the same subsystem; its covariances are computed exactly from
int_0^inf k J_nu(kR)^2/(k^2+c^2) dk = I_nu(cR) K_nu(cR) and 1/omega = (2/pi) int_0^inf dt/(omega^2+t^2) (no
k cut-off).  For the massless control the truncation to A modes lowers the ratio by about b/A (Part A).

Test functions: radial profile phi(r) = exp(-(r-r0)^2/(2 w^2)), u = r^{(D-1)/2} phi, projected on the A modes
(the projected function is the test function, used identically in numerator and denominator).  Printed:
   ratio = u^T N u / int_0^R beta(r) u(r)^2 dr       (1 = conformal Killing weight).

Usage: modular_ball_check.py     no arguments, deterministic; runtime about 6-8 minutes on 2 cores, memory < 0.5 GB.
"""
import sys
import time
from multiprocessing import Pool
import numpy as np
import mpmath as mp

DPS = 60
mp.mp.dps = DPS


def set_dps(d):
    global DPS
    DPS = d
    mp.mp.dps = d


def fixbits():
    return int(DPS * 3.33) + 40


def gl(n):
    xs, ws = [], []
    for i in range(1, n + 1):
        x = mp.cos(mp.pi * (i - mp.mpf(1) / 4) / (n + mp.mpf(1) / 2))
        for _ in range(200):
            p0, p1 = mp.mpf(1), x
            for k in range(2, n + 1):
                p0, p1 = p1, ((2 * k - 1) * x * p1 - (k - 1) * p0) / k
            dp = n * (x * p1 - p0) / (x * x - 1)
            dx = p1 / dp
            x -= dx
            if abs(dx) < mp.mpf(10) ** (-DPS - 3):
                break
        p0, p1 = mp.mpf(1), x
        for k in range(2, n + 1):
            p0, p1 = p1, ((2 * k - 1) * x * p1 - (k - 1) * p0) / k
        dp = n * (x * p1 - p0) / (x * x - 1)
        xs.append(x); ws.append(2 / ((1 - x * x) * dp * dp))
    return xs, ws


_GL = {}


def glc(n):
    key = (n, DPS)
    if key not in _GL:
        _GL[key] = gl(n)
    return _GL[key]


def kgrid(kappa, kmax, panel, npt=32):
    edges = [mp.mpf(0)]
    e = kappa / 4
    while e < panel:
        edges.append(e); e *= 2
    e = edges[-1] + panel
    while e < kmax:
        edges.append(e); e += panel
    edges.append(kmax)
    xg, wg = glc(npt)
    ks, ws = [], []
    for a, b in zip(edges[:-1], edges[1:]):
        h = (b - a) / 2; c = (b + a) / 2
        for x, w in zip(xg, wg):
            ks.append(c + h * x); ws.append(h * w)
    return ks, ws


def zeros(nu, R, amax):
    al = []
    a = 1
    while True:
        z = mp.besseljzero(nu, a)
        if z / R > amax:
            break
        al.append(z / R); a += 1
    return al


def node_fg(k, m):
    om = mp.sqrt(2 * (1 - mp.exp(-k * k / 2)) + m * m)
    return 1 / (2 * om), om / 2


def build_node(nu, R, m, amax, kmax=15, panel=mp.mpf('0.125')):
    """Subsystem covariances X, P (A x A) of the node model (population level, xi = 1) on the first A Dirichlet
    modes of the ball of radius R in angular sector of Bessel order nu."""
    R = mp.mpf(R); m = mp.mpf(m)
    al = zeros(nu, R, amax)
    A = len(al)
    sg = [mp.sign(mp.besselj(nu + 1, a * R)) for a in al]
    kappa = mp.sqrt(2 * mp.log(1 + m * m / 2))
    ks, ws = kgrid(kappa, mp.mpf(kmax), panel)
    f0 = 1 / (2 * mp.sqrt(2 + m * m)); g0 = mp.sqrt(2 + m * m) / 2
    PB = fixbits(); sc = mp.mpf(2) ** PB
    Phi = np.empty((A, len(ks)), dtype=object)
    wf = np.empty(len(ks), dtype=object); wg_ = np.empty(len(ks), dtype=object)
    for j, (k, w) in enumerate(zip(ks, ws)):
        J = mp.besselj(nu, k * R)
        f, g = node_fg(k, m)
        wf[j] = int(mp.nint(w * k * (f - f0) * sc))
        wg_[j] = int(mp.nint(w * k * (g - g0) * sc))
        for a in range(A):
            Phi[a, j] = int(mp.nint(mp.sqrt(2) * sg[a] * al[a] * J / (al[a] ** 2 - k * k) * sc))
    Fi = (Phi * wf[None, :]).dot(Phi.T)
    Gi = (Phi * wg_[None, :]).dot(Phi.T)
    sc3 = sc ** 3
    X = mp.matrix(A, A); P = mp.matrix(A, A)
    for a in range(A):
        for b in range(A):
            X[a, b] = mp.mpf(Fi[a, b]) / sc3 + (f0 if a == b else 0)
            P[a, b] = mp.mpf(Gi[a, b]) / sc3 + (g0 if a == b else 0)
    return al, sg, X, P


def build_cont(nu, R, m, amax, h=mp.mpf('0.03')):
    """Same for the free continuum scalar field of mass m (omega^2 = k^2 + m^2), exact by
    int_0^inf k J_nu(kR)^2/(k^2+c^2) dk = I_nu(cR) K_nu(cR) and the resolvent representation of omega^{-1}."""
    R = mp.mpf(R); m = mp.mpf(m)
    al = zeros(nu, R, amax)
    A = len(al)
    sg = [mp.sign(mp.besselj(nu + 1, a * R)) for a in al]
    # double exponential grid t = exp((pi/2) sinh u)
    us = []
    u = mp.mpf(-6)
    while u <= 5:
        us.append(u); u += h
    T = [mp.mpf(0)] * A; U = [mp.mpf(0)] * A
    for u in us:
        t = mp.exp(mp.pi / 2 * mp.sinh(u))
        dt = t * mp.pi / 2 * mp.cosh(u) * h
        c = mp.sqrt(t * t + m * m)
        z = c * R
        ik = mp.besseli(nu, z) * mp.besselk(nu, z)
        if not mp.isfinite(ik):
            continue
        q = ik * dt
        for a in range(A):
            d = al[a] ** 2 + c * c
            T[a] += q / d; U[a] += q / (d * d)
    X = mp.matrix(A, A); P = mp.matrix(A, A)
    for a in range(A):
        for b in range(A):
            pre = 2 * sg[a] * sg[b] * al[a] * al[b] / mp.pi
            if a == b:
                w = 1j * al[a]; z = w * R
                I = mp.besseli(nu, z); K = mp.besselk(nu, z)
                Ip = mp.besseli(nu + 1, z) + nu / z * I; Kp = -mp.besselk(nu + 1, z) + nu / z * K
                Ga = mp.re(-R / (2 * w) * (Ip * K + I * Kp))
                X[a, b] = pre * (U[a] + Ga * mp.pi / (2 * mp.sqrt(al[a] ** 2 + m * m)))
            else:
                X[a, b] = pre * (T[a] - T[b]) / (al[b] ** 2 - al[a] ** 2)
    Y = [mp.sqrt(2) * sg[b] * al[b] * T[b] / mp.pi for b in range(A)]
    for a in range(A):
        for b in range(A):
            pab = (al[a] ** 2 + m * m) * X[a, b] - mp.sqrt(2) * sg[a] * al[a] * Y[b]
            pba = (al[b] ** 2 + m * m) * X[b, a] - mp.sqrt(2) * sg[b] * al[b] * Y[a]
            P[a, b] = (pab + pba) / 2
    return al, sg, X, P


def modular_N(X, P):
    A = X.rows
    ep, Up = mp.eigsy(P)
    Ph = Up * mp.diag([mp.sqrt(e) for e in ep]) * Up.T
    Pmh = Up * mp.diag([1 / mp.sqrt(e) for e in ep]) * Up.T
    M = Ph * X * Ph
    for i in range(A):
        M[i, i] -= mp.mpf(1) / 4
    M = (M + M.T) / 2
    dl, Uv = mp.eigsy(M)
    thr = mp.mpf(10) ** (-(DPS - 10))
    w = []; nclip = 0; epsl = []
    for d in dl:
        if d < thr:
            d = thr; nclip += 1
        nu = mp.sqrt(mp.mpf(1) / 4 + d)
        eps = mp.log((nu + mp.mpf(1) / 2) ** 2 / d)
        w.append(eps * nu); epsl.append(eps)
    N = Pmh * Uv * mp.diag(w) * Uv.T * Pmh
    return N, nclip, epsl


def basis_on_grid(nu, R, al, sg, rs):
    """psi_a(r) = N_a sqrt(r) J_nu(alpha_a r), orthonormal on [0,R] w.r.t. dr (double precision values)."""
    out = np.zeros((len(al), len(rs)))
    with mp.workdps(25):
        for a, (alp, s) in enumerate(zip(al, sg)):
            Na = mp.sqrt(2) / (R * abs(mp.besselj(nu + 1, alp * R)))
            for i, r in enumerate(rs):
                out[a, i] = float(Na * mp.sqrt(r) * mp.besselj(nu, alp * r))
    return out


WIDTHS = (1.0, 2.0, 4.0)


def run(cfg):
    model, nu, R, m, amax, dps, rows, widths = cfg
    set_dps(dps)
    nu = mp.mpf(nu)
    D = 2 if nu == int(nu) else 3
    t0 = time.time()
    al, sg, X, P = (build_node if model == 'node' else build_cont)(nu, R, mp.mpf(m), amax)
    N, nclip, eps = modular_N(X, P)
    A = len(al)
    xg, wg = np.polynomial.legendre.leggauss(500)
    rs = 0.5 * R * (xg + 1); wr = 0.5 * R * wg
    B = basis_on_grid(nu, R, al, sg, rs)
    beta = np.pi * (R ** 2 - rs ** 2) / R
    Nf = np.array([[float(N[i, j]) for j in range(A)] for i in range(A)])
    out = []
    for r0 in rows:
        res = []
        for w in widths:
            u = rs ** ((D - 1) / 2) * np.exp(-(rs - r0) ** 2 / (2 * w * w))
            c = B @ (wr * u); up = c @ B
            res.append(float(c @ Nf @ c) / float(np.sum(wr * beta * up ** 2)))
        out.append((r0, res))
    return dict(model=model, D=D, nu=float(nu), R=R, m=m, amax=amax, dps=dps, A=A, nclip=nclip,
                epsmax=float(max(eps)), out=out, widths=widths, time=time.time() - t0)


def show(r, label=''):
    sec = int(round(r['nu'])) if r['D'] == 2 else int(round(r['nu'] - 0.5))
    print(f"  {label}{r['model']:4s} D={r['D']} {'mu' if r['D'] == 2 else 'l '}={sec:<2d} R={r['R']:<4g} m={r['m']:<6g}"
          f" mR={r['m'] * r['R']:<5g} amax={r['amax']:<3g} A={r['A']:<3d} dps={r['dps']} clipped={r['nclip']}"
          f"  [{r['time']:.0f}s]")
    print("        r0/R   R-r0  " + "".join(f"   w={w:<4g}" for w in r['widths']))
    for r0, res in r['out']:
        print(f"       {r0 / r['R']:5.3f} {r['R'] - r0:6.2f}  " + "".join(f"  {v:8.4f}" for v in res))


def main():
    sys.stdout.reconfigure(line_buffering=True)
    T0 = time.time()
    cfgA = [('cont', 0, 8.0, 0.0, a, 60, [0.0, 2.0, 4.0, 6.0], (1.0, 1.5, 2.0)) for a in (10, 15, 20)]
    cfgA += [('cont', 0.5, 8.0, 0.0, a, 60, [0.0, 2.0, 4.0, 6.0], (1.0, 1.5, 2.0)) for a in (10, 20)]
    rowsB = [0.0, 4.0, 8.0, 12.0]
    cfgB = [(mod, nu, 16.0, m, 10, 60, rowsB, WIDTHS) for nu in (0, 0.5) for m in (0.01, 0.125, 0.5)
            for mod in ('node', 'cont')]
    cfgB += [('cont', nu, 16.0, 0.0, 10, 60, rowsB, WIDTHS) for nu in (0, 0.5)]
    cfgC = [(mod, nu, 16.0, 0.01, 10, 60, [4.0, 8.0, 12.0], WIDTHS) for nu in (2, 8, 2.5, 8.5)
            for mod in ('node', 'cont')]
    cfgD = [(mod, 0, R, 0.01, 10, 60, [R - 3.0, R - 5.0], (1.0, 2.0)) for R in (8.0, 16.0, 32.0)
            for mod in ('node', 'cont')]
    cfgE = [('node', 0, 16.0, 0.01, 14, 60, rowsB, WIDTHS), ('node', 0, 8.0, 0.25, 10, 75, [0.0, 4.0], (1.0, 2.0)),
            ('node', 0, 8.0, 0.25, 10, 60, [0.0, 4.0], (1.0, 2.0))]
    allc = cfgA + cfgB + cfgC + cfgD + cfgE
    with Pool(2) as pool:
        res = pool.map(run, allc, chunksize=1)
    i = 0
    print("Part A. Control: massless continuum field (conformal: exact answer 1), convergence in the number A of modes")
    for k in range(len(cfgA)):
        show(res[i]); i += 1
    for D, idx in ((2, (1, 2)), (3, (3, 4))):
        r1, r2 = res[idx[0]], res[idx[1]]
        ex = [[(r2['A'] * v2 - r1['A'] * v1) / (r2['A'] - r1['A']) for v1, v2 in zip(a[1], b[1])]
              for a, b in zip(r1['out'], r2['out'])]
        print(f"  D={D}: extrapolation a - b/A from A={r1['A']},{r2['A']}: " +
              "; ".join(f"r0={a[0]:g}: " + ", ".join(f"{v:.4f}" for v in e) for a, e in zip(r1['out'], ex)))
    print("\nPart B. Node model against continuum field of the same mass, R = 16 xi, sector 0, bump widths w (in xi);"
          " last two blocks: massless continuum field (truncation reference at A ~ 50)")
    for k in range(len(cfgB)):
        show(res[i]); i += 1
    print("\nPart C. Angular-momentum dependence, R = 16, m = 0.01")
    for k in range(len(cfgC)):
        show(res[i]); i += 1
    print("\nPart D. Half-space limit: bumps at fixed distance R - r0 = 3, 5 from the boundary, R = 8, 16, 32 (m = 0.01)")
    for k in range(len(cfgD)):
        show(res[i]); i += 1
    print("\nPart E. Discretisation checks: node model with amax = 14 (compare Part B), dps 75 against 60")
    for k in range(len(cfgE)):
        show(res[i]); i += 1
    print(f"\ntotal runtime {time.time() - T0:.0f} s")


if __name__ == "__main__":
    main()
